import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { webcrypto } from 'node:crypto';
import { createLanServer } from '../desktop/server.mjs';
const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'vpvi-operator-test-'));
const scope = { AbortController, URLSearchParams, setTimeout, clearTimeout, crypto: webcrypto, fetch };
scope.window = scope; vm.runInNewContext(await fs.readFile(new URL('../sync-client.js', import.meta.url), 'utf8'), scope);
const Client = scope.VictoryPVISyncClient;
const app = await createLanServer({ dataDir, port: 0, pollMs: 80, leaseMs: 500 });
const ip = Object.values(os.networkInterfaces()).flat().find(item => item.family === 'IPv4' && !item.internal)?.address;
assert.ok(ip, 'An actual LAN interface is needed to verify remote operator writes');
const local = `http://127.0.0.1:${app.port}`, remote = `http://${ip}:${app.port}`;
const transport = base => (url, options) => fetch(base + url, options);
const record = count => ({ schemaVersion: 7, counts: { test: count } });
const wait = async (check, label) => { for (let n = 0; n < 500; n++) { if (check()) return; await new Promise(r => setTimeout(r, 20)); } throw new Error(label); };
const peers = [];
const make = options => { const client = new Client(options); peers.push(client); return client; };
let desktopSeen = [], phoneSeen = [], tabletSeen = [], pending, offline = false;
const desktop = make({ fetch: transport(local), getSnapshot: () => record(1), onSnapshot: p => desktopSeen.push(p) });
const tablet = make({ fetch: transport(remote), onSnapshot: p => tabletSeen.push(p) });
try {
  const remoteInfo = await (await fetch(remote + '/api/lan/info')).json();
  assert.equal(remoteInfo.isLocalComputer, false);
  const initial = await desktop.connect({ autoStart: true, deviceId: 'desktop' });
  assert.equal(initial.role, 'host');
  await wait(() => !desktop.pending, 'Initial desktop save');
  await tablet.connect({ deviceId: 'tablet', roomId: app.roomId });
  let phone = make({ fetch: (url, options) => offline ? Promise.reject(new Error('offline')) : transport(remote)(url, options),
    onSnapshot: p => phoneSeen.push(p), onPending: d => { pending = d; } });
  await phone.connect({ deviceId: 'phone', roomId: app.roomId });
  const claimId = 'phone-takeover';
  const epoch = phone.operatorRevision;
  const control = await phone.connect({ role: 'host', deviceId: 'phone', roomId: app.roomId, claimId,
    expectedOperatorRevision: epoch, onRestore: p => phoneSeen.push(p) });
  assert.equal(control.role, 'host');
  assert.equal(phoneSeen.at(-1).counts.test, 1);
  await wait(() => desktop.role === 'mirror', 'Desktop becomes a live mirror');
  phone.sendSnapshot(record(2), 1);
  await wait(() => desktopSeen.at(-1)?.counts.test === 2 && tabletSeen.at(-1)?.counts.test === 2, 'Remote phone writes reach desktop and tablet');
  const writerId = phone.writerId, sessionId = phone.sessionId;
  offline = true;
  phone.sendSnapshot(record(3), 2);
  phone.disconnect();
  phone = make({ fetch: transport(remote), sessionId, onSnapshot: p => phoneSeen.push(p) });
  const resumed = await phone.connect({ deviceId: 'phone', roomId: app.roomId, resumeWriterId: writerId, draft: pending, onRestore: p => phoneSeen.push(p) });
  assert.equal(resumed.role, 'host'); assert.equal(resumed.writerId, writerId);
  assert.equal(phoneSeen.at(-1).counts.test, 3);
  await wait(() => desktopSeen.at(-1)?.counts.test === 3, 'Phone refresh restores its unacknowledged draft');
  const freshDesktop = make({ fetch: transport(local), onSnapshot: p => desktopSeen.push(p) });
  assert.equal((await freshDesktop.connect({ autoStart: true, deviceId: 'desktop' })).role, 'mirror', 'Opening the desktop cannot steal mobile control');
  await freshDesktop.connect({ role: 'host', deviceId: 'desktop', onRestore: p => desktopSeen.push(p) });
  await wait(() => phone.role === 'mirror', 'Phone follows after desktop explicitly takes over');
  freshDesktop.sendSnapshot(record(4), 1);
  await wait(() => phoneSeen.at(-1)?.counts.test === 4, 'Former phone operator stays connected and follows');
  const staleWrite = await fetch(remote + '/api/lan/snapshot', { method: 'POST', body: JSON.stringify({ writerId, clientRevision: 90, payload: record(999) }) });
  assert.equal(staleWrite.status, 409);
  const staleClaim = await fetch(remote + '/api/lan/host', { method: 'POST', body: JSON.stringify({ roomId: app.roomId, deviceId: 'phone', sessionId, claimId, takeover: true, expectedOperatorRevision: epoch }) });
  assert.equal(staleClaim.status, 409, 'A late retry of an old claim cannot steal control back');
  assert.equal(JSON.parse(await fs.readFile(path.join(dataDir, 'record.json'), 'utf8')).snapshot.payload.counts.test, 4);
  assert.equal((await fetch(remote + '/api/lan/shutdown', { method: 'POST' })).status, 403, 'Mobile operation does not expose process shutdown');
  console.log('mobile-operator-smoke: actual LAN writes, live handover both ways, mobile refresh with pending draft, desktop reopen, stale claim/write rejection passed');
} finally { for (const client of peers) client.disconnect(); await app.close(); await fs.rm(dataDir, { recursive: true, force: true }); }
